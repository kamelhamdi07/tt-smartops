-- Espace client : comptes CLIENT et réclamations traitées par le chef de l'équipe concernée.

-- Le CHECK du rôle a été créé sans nom explicite : on le retrouve par sa définition
DO $$
DECLARE c TEXT;
BEGIN
    FOR c IN SELECT conname FROM pg_constraint
             WHERE conrelid = 'users'::regclass AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%role%'
    LOOP
        EXECUTE 'ALTER TABLE users DROP CONSTRAINT ' || quote_ident(c);
    END LOOP;
END $$;
ALTER TABLE users ADD CONSTRAINT users_role_check
    CHECK (role IN ('ADMIN', 'RH', 'RESPONSABLE_TECHNIQUE', 'TECHNICIEN', 'EMPLOYE', 'CLIENT'));

-- Coordonnées des comptes CLIENT (les comptes du personnel passent par la fiche employé)
ALTER TABLE users ADD COLUMN full_name VARCHAR(150);
ALTER TABLE users ADD COLUMN phone     VARCHAR(30);
ALTER TABLE users ADD COLUMN address   VARCHAR(255);

-- Routage : chaque catégorie de réclamation est prise en charge par une seule équipe
CREATE TABLE team_reclamation_categories (
    team_id  BIGINT      NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
    category VARCHAR(30) NOT NULL UNIQUE
             CHECK (category IN ('WIFI', 'ADSL', 'FIBRE', 'TELEPHONE_FIXE', 'MOBILE', 'AUTRE')),
    PRIMARY KEY (team_id, category)
);

CREATE TABLE reclamations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference       VARCHAR(30)   NOT NULL UNIQUE,
    client_id       BIGINT        NOT NULL REFERENCES users (id),
    category        VARCHAR(30)   NOT NULL
                    CHECK (category IN ('WIFI', 'ADSL', 'FIBRE', 'TELEPHONE_FIXE', 'MOBILE', 'AUTRE')),
    title           VARCHAR(200)  NOT NULL,
    description     VARCHAR(2000) NOT NULL,
    address         VARCHAR(255)  NOT NULL,
    phone           VARCHAR(30)   NOT NULL,
    status          VARCHAR(20)   NOT NULL
                    CHECK (status IN ('NOUVELLE', 'AFFECTEE', 'EN_COURS', 'RESOLUE', 'ANNULEE')),
    team_id         BIGINT        REFERENCES teams (id),
    intervention_id BIGINT        UNIQUE REFERENCES interventions (id),
    resolved_at     TIMESTAMP,
    created_at      TIMESTAMP     NOT NULL,
    updated_at      TIMESTAMP     NOT NULL
);
CREATE INDEX idx_reclamation_client ON reclamations (client_id, created_at DESC);
CREATE INDEX idx_reclamation_team ON reclamations (team_id, status);
CREATE SEQUENCE reclamation_ref_seq;
