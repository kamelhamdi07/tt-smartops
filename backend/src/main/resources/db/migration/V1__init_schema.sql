CREATE TABLE departments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(20)  NOT NULL UNIQUE,
    name         VARCHAR(120) NOT NULL,
    description  VARCHAR(500),
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL
);

CREATE TABLE teams (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    description   VARCHAR(500),
    department_id BIGINT       NOT NULL REFERENCES departments (id),
    leader_id     BIGINT,
    created_at    TIMESTAMP    NOT NULL,
    updated_at    TIMESTAMP    NOT NULL,
    CONSTRAINT uq_team_name_department UNIQUE (department_id, name)
);

CREATE TABLE employees (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricule     VARCHAR(20)  NOT NULL UNIQUE,
    first_name    VARCHAR(80)  NOT NULL,
    last_name     VARCHAR(80)  NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    phone         VARCHAR(30),
    job_title     VARCHAR(120) NOT NULL,
    hire_date     DATE         NOT NULL,
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('ACTIF', 'SUSPENDU', 'INACTIF')),
    technician    BOOLEAN      NOT NULL DEFAULT FALSE,
    specialty     VARCHAR(30),
    department_id BIGINT REFERENCES departments (id),
    team_id       BIGINT REFERENCES teams (id),
    created_at    TIMESTAMP    NOT NULL,
    updated_at    TIMESTAMP    NOT NULL,
    CONSTRAINT ck_technician_specialty CHECK (technician = FALSE OR specialty IS NOT NULL)
);

ALTER TABLE teams ADD CONSTRAINT fk_team_leader FOREIGN KEY (leader_id) REFERENCES employees (id);

CREATE INDEX idx_employees_department ON employees (department_id);
CREATE INDEX idx_employees_team ON employees (team_id);
CREATE INDEX idx_employees_technician ON employees (technician, status);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(30)  NOT NULL
                  CHECK (role IN ('ADMIN', 'RH', 'RESPONSABLE_TECHNIQUE', 'TECHNICIEN', 'EMPLOYE')),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    employee_id   BIGINT UNIQUE REFERENCES employees (id),
    last_login_at TIMESTAMP,
    created_at    TIMESTAMP    NOT NULL,
    updated_at    TIMESTAMP    NOT NULL
);

CREATE TABLE leave_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id      BIGINT      NOT NULL REFERENCES employees (id),
    type             VARCHAR(20) NOT NULL,
    start_date       DATE        NOT NULL,
    end_date         DATE        NOT NULL,
    working_days     INTEGER     NOT NULL,
    comment          VARCHAR(500),
    status           VARCHAR(20) NOT NULL CHECK (status IN ('EN_ATTENTE', 'APPROUVEE', 'REFUSEE', 'ANNULEE')),
    decision_comment VARCHAR(500),
    processed_at     TIMESTAMP,
    processed_by     BIGINT REFERENCES users (id),
    created_at       TIMESTAMP   NOT NULL,
    updated_at       TIMESTAMP   NOT NULL,
    CONSTRAINT ck_leave_dates CHECK (end_date >= start_date)
);
CREATE INDEX idx_leave_employee_period ON leave_requests (employee_id, start_date, end_date);
CREATE INDEX idx_leave_status ON leave_requests (status);

CREATE TABLE absences (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT      NOT NULL REFERENCES employees (id),
    type        VARCHAR(20) NOT NULL,
    start_date  DATE        NOT NULL,
    end_date    DATE        NOT NULL,
    reason      VARCHAR(500),
    justified   BOOLEAN     NOT NULL DEFAULT FALSE,
    recorded_by BIGINT REFERENCES users (id),
    created_at  TIMESTAMP   NOT NULL,
    updated_at  TIMESTAMP   NOT NULL,
    CONSTRAINT ck_absence_dates CHECK (end_date >= start_date)
);
CREATE INDEX idx_absence_employee_period ON absences (employee_id, start_date, end_date);

CREATE TABLE equipment (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference             VARCHAR(40)  NOT NULL UNIQUE,
    name                  VARCHAR(150) NOT NULL,
    type                  VARCHAR(60)  NOT NULL,
    status                VARCHAR(20)  NOT NULL
                          CHECK (status IN ('DISPONIBLE', 'AFFECTE', 'EN_MAINTENANCE', 'HORS_SERVICE')),
    location              VARCHAR(150),
    responsible_id        BIGINT REFERENCES employees (id),
    last_maintenance_date DATE,
    next_maintenance_date DATE,
    notes                 VARCHAR(1000),
    created_at            TIMESTAMP    NOT NULL,
    updated_at            TIMESTAMP    NOT NULL
);

CREATE TABLE vehicles (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number          VARCHAR(20)  NOT NULL UNIQUE,
    brand_model           VARCHAR(100) NOT NULL,
    type                  VARCHAR(40)  NOT NULL,
    status                VARCHAR(20)  NOT NULL
                          CHECK (status IN ('DISPONIBLE', 'AFFECTE', 'EN_MAINTENANCE', 'HORS_SERVICE')),
    mileage               INTEGER      NOT NULL DEFAULT 0 CHECK (mileage >= 0),
    last_maintenance_date DATE,
    team_id               BIGINT REFERENCES teams (id),
    created_at            TIMESTAMP    NOT NULL,
    updated_at            TIMESTAMP    NOT NULL
);

CREATE SEQUENCE intervention_ref_seq START 1;

CREATE TABLE interventions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference          VARCHAR(20)  NOT NULL UNIQUE,
    title              VARCHAR(200) NOT NULL,
    description        TEXT,
    type               VARCHAR(30)  NOT NULL,
    priority           VARCHAR(20)  NOT NULL CHECK (priority IN ('BASSE', 'NORMALE', 'HAUTE', 'CRITIQUE')),
    location           VARCHAR(255) NOT NULL,
    required_specialty VARCHAR(30),
    planned_start      TIMESTAMP,
    planned_end        TIMESTAMP,
    due_date           DATE,
    status             VARCHAR(20)  NOT NULL CHECK (status IN ('NOUVELLE', 'PLANIFIEE', 'AFFECTEE', 'EN_COURS',
                                                              'SUSPENDUE', 'TERMINEE', 'VALIDEE', 'ANNULEE')),
    team_id            BIGINT REFERENCES teams (id),
    equipment_id       BIGINT REFERENCES equipment (id),
    vehicle_id         BIGINT REFERENCES vehicles (id),
    created_by         BIGINT       NOT NULL REFERENCES users (id),
    actual_start       TIMESTAMP,
    actual_end         TIMESTAMP,
    cancel_reason      VARCHAR(500),
    created_at         TIMESTAMP    NOT NULL,
    updated_at         TIMESTAMP    NOT NULL,
    CONSTRAINT ck_intervention_schedule CHECK (
        (planned_start IS NULL AND planned_end IS NULL)
        OR (planned_start IS NOT NULL AND planned_end IS NOT NULL AND planned_end > planned_start))
);
CREATE INDEX idx_intervention_status ON interventions (status);
CREATE INDEX idx_intervention_period ON interventions (planned_start, planned_end);
CREATE INDEX idx_intervention_equipment ON interventions (equipment_id);
CREATE INDEX idx_intervention_vehicle ON interventions (vehicle_id);

CREATE TABLE intervention_assignments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intervention_id BIGINT    NOT NULL REFERENCES interventions (id) ON DELETE CASCADE,
    technician_id   BIGINT    NOT NULL REFERENCES employees (id),
    assigned_by     BIGINT    NOT NULL REFERENCES users (id),
    assigned_at     TIMESTAMP NOT NULL,
    acknowledged_at TIMESTAMP,
    CONSTRAINT uq_assignment UNIQUE (intervention_id, technician_id)
);
CREATE INDEX idx_assignment_technician ON intervention_assignments (technician_id);

CREATE TABLE intervention_status_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intervention_id BIGINT       NOT NULL REFERENCES interventions (id) ON DELETE CASCADE,
    from_status     VARCHAR(20),
    to_status       VARCHAR(20)  NOT NULL,
    changed_by      VARCHAR(150) NOT NULL,
    changed_at      TIMESTAMP    NOT NULL,
    comment         VARCHAR(500)
);
CREATE INDEX idx_history_intervention ON intervention_status_history (intervention_id);

CREATE TABLE intervention_reports (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intervention_id  BIGINT      NOT NULL UNIQUE REFERENCES interventions (id),
    author_id        BIGINT      NOT NULL REFERENCES employees (id),
    work_start       TIMESTAMP,
    work_end         TIMESTAMP,
    problem_found    TEXT,
    diagnosis        TEXT,
    solution_applied TEXT,
    materials_used   TEXT,
    replaced_parts   TEXT,
    observations     TEXT,
    result           VARCHAR(30),
    status           VARCHAR(20) NOT NULL CHECK (status IN ('BROUILLON', 'SOUMIS', 'A_CORRIGER', 'VALIDE')),
    submitted_at     TIMESTAMP,
    review_comment   VARCHAR(1000),
    reviewed_by      BIGINT REFERENCES users (id),
    reviewed_at      TIMESTAMP,
    created_at       TIMESTAMP   NOT NULL,
    updated_at       TIMESTAMP   NOT NULL
);

CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type         VARCHAR(40)   NOT NULL,
    title        VARCHAR(200)  NOT NULL,
    message      VARCHAR(1000) NOT NULL,
    link         VARCHAR(255),
    is_read      BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMP     NOT NULL
);
CREATE INDEX idx_notification_recipient ON notifications (recipient_id, is_read, created_at DESC);

CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT,
    actor_email VARCHAR(150) NOT NULL,
    action      VARCHAR(60)  NOT NULL,
    entity_type VARCHAR(60)  NOT NULL,
    entity_id   BIGINT,
    details     TEXT,
    created_at  TIMESTAMP    NOT NULL
);
CREATE INDEX idx_audit_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX idx_audit_created ON audit_logs (created_at DESC);
